/**
 * Response headers applied to every SSR response.
 *
 * The CSP is enforced in layers:
 *  - frame-ancestors: clickjacking / embedding defence.
 *  - object-src / base-uri: plugin and <base> hijacking.
 *  - script-src: only 'self', TanStack Start's inline hydration scripts
 *    (<Scripts />), and the Razorpay checkout script (loaded on demand; see
 *    subscription.ts loadRazorpayScript). 'unsafe-inline' is granted because
 *    Start inlines its hydration payload without a nonce; tightening further
 *    (nonces / strict-dynamic) requires nonce plumbing through Start's
 *    script injector.
 *  - connect-src: Supabase REST + realtime WS, Resend webhooks are
 *    server-side only. Razorpay API calls are from the browser during
 *    checkout so checkout.razorpay.com is whitelisted.
 *  - img-src: Supabase storage signed URLs + data/blob for local previews.
 *  - font-src: self-hosted fonts in /fonts/.
 *
 * Tightening further (adding nonces for inline styles, strict-dynamic for
 * scripts) requires nonce plumbing through TanStack Start's script injector.
 */
const FRAME_ANCESTORS_PROD = "'self'";

// Dev allows localhost and internal development tools
const FRAME_ANCESTORS_DEV = [
  "'self'",
  "http://localhost:3000",
  "https://lovable.dev",
  "https://*.lovable.app",
  "https://*.lovableproject.com",
  "https://*.lovableproject-dev.com",
].join(" ");

/**
 * The Content-Security-Policy for an environment.
 *
 * Exported so the production policy can be asserted directly. The previous
 * test read `import.meta.env.PROD`, which is false under Vitest, so the
 * production assertions it wrapped never ran — the clickjacking defence was
 * effectively untested.
 */
export function buildCsp(isProd: boolean): string {
  const frameAncestors = isProd ? FRAME_ANCESTORS_PROD : FRAME_ANCESTORS_DEV;
  return [
    "default-src 'self'",
    "form-action 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    `frame-ancestors ${frameAncestors}`,
    // Allow our own scripts, inline hydration scripts (<Scripts /> from TanStack Start),
    // and the Razorpay checkout widget.
    "script-src 'self' 'unsafe-inline' https://checkout.razorpay.com",
    // Styles: allow self and inline styles generated by UI components
    "style-src 'self' 'unsafe-inline'",
    // Supabase REST, realtime WS, and Razorpay from the browser.
    "connect-src 'self' https://*.supabase.co wss://*.supabase.co https://api.razorpay.com https://checkout.razorpay.com",
    // Storage signed URLs (Supabase), data URIs for previews, blob for
    // canvas-watermarked images.
    "img-src 'self' data: blob: https://*.supabase.co",
    // Self-hosted fonts in /fonts/.
    "font-src 'self' data:",
  ].join("; ");
}

/**
 * The response headers.
 *
 * `isProd` is a parameter with the real environment as its default, so the
 * production policy — which is the one that matters — can be asserted
 * directly. Reading `import.meta.env.PROD` inside the function made the HSTS
 * branch unreachable in tests, because that flag is false under Vitest.
 */
export function securityHeaders(
  isProd: boolean = import.meta.env["PROD"] === true,
): Record<string, string> {
  const headers: Record<string, string> = {
    "content-security-policy": buildCsp(isProd),
    "x-content-type-options": "nosniff",
    "referrer-policy": "strict-origin-when-cross-origin",
    "permissions-policy": "camera=(self), microphone=(self), geolocation=()",
    // OAuth popups need to keep the opener reference.
    "cross-origin-opener-policy": "same-origin-allow-popups",
    // Defence in depth: the browser must not run our resources cross-origin.
    "cross-origin-resource-policy": "same-origin",
    // No plugin content, no cross-domain policy files.
    "x-permitted-cross-domain-policies": "none",
  };
  if (isProd) {
    headers["strict-transport-security"] = "max-age=31536000; includeSubDomains";
  }
  return headers;
}

/**
 * The member-only route prefixes.
 *
 * These pages are rendered with `ssr: false`, so no member data is in the
 * document today — but their responses must never be cacheable anyway. The
 * moment any part of the authenticated tree is server-rendered, a cached
 * document becomes a member's page sitting in a shared browser's disk cache.
 * Getting the header right now means that change cannot introduce a leak.
 */
const AUTHENTICATED_PATH_PREFIXES = [
  "/dashboard",
  "/members",
  "/connections",
  "/messages",
  "/calls",
  "/call/",
  "/shortlist",
  "/notifications",
  "/copilots",
  "/copilot-invite",
  "/onboarding",
  "/verification",
  "/settings",
  "/admin",
];

export function isAuthenticatedPath(pathname: string): boolean {
  return AUTHENTICATED_PATH_PREFIXES.some(
    (prefix) => pathname === prefix || pathname.startsWith(prefix),
  );
}

/**
 * Cache policy per response.
 *
 * Member-only pages: `private, no-store`. The public pages are revalidated
 * every time, so a deploy is picked up immediately but a repeat visit does not
 * re-download the shell.
 */
export function cacheControlFor(pathname: string): string {
  return isAuthenticatedPath(pathname)
    ? "private, no-store, max-age=0"
    : "public, max-age=0, must-revalidate";
}

/** Adds the headers above without ever throwing on an immutable Response. */
export function withSecurityHeaders(response: Response): Response {
  for (const [key, value] of Object.entries(securityHeaders())) {
    if (response.headers.has(key)) continue;
    try {
      response.headers.set(key, value);
    } catch {
      /* immutable headers — leave the response untouched */
    }
  }
  return response;
}
